async def seed_regions(session: AsyncSession) -> None:
    for (
        code,
        name_ru,
        ics_section,
        ref_system,
        ref_code,
        description,
    ) in REGION_DATA:
        result = await session.execute(
            select(Region).where(Region.code == code)
        )
        existing = result.scalar_one_or_none()

        if existing is None:
            session.add(
                Region(
                    code=code,
                    name_ru=name_ru,
                    ics_section=ics_section,
                    ref_system=ref_system,
                    ref_code=ref_code,
                    description=description,
                )
            )
        else:
            existing.name_ru = name_ru
            existing.ics_section = ics_section
            existing.ref_system = ref_system
            existing.ref_code = ref_code
            existing.description = description

    await session.commit()

